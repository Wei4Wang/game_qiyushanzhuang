def chapter_text(char, rng):
    out = []
    for title, beats in char["chapters"]:
        out.append("　　【" + title + "】")
        out.append(pick(ATMOSPHERE, rng) + pick(NIGHT, rng) + pick(DETAIL, rng))
        out.append(gen_flashback(char, rng))
        out.append("")
        for b in beats:
            out.append("　　" + b + pick(DETAIL, rng) + pick(EMO[char["tone"]], rng))
            out.append("　　" + pick(RAIN, rng) + pick(REFLECTION, rng) + pick(DETAIL, rng))
            for _ in range(EXPAND_LEVEL):
                out.append(long_atmosphere(rng) if rng.random() < 0.5 else inner_monologue(char, rng))
            out.append("　　" + pick(NIGHT, rng) + pick(EMO[char["tone"]], rng) + pick(TRANSITION, rng))
            out.append("")
        out.append("")
        out.append("　　" + pick(END_SCENE, rng) + pick(CLIFFHANGER, rng) + pick(DETAIL, rng))
        out.append("")
    return "\n".join(out)

